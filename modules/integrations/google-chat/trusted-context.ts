/**
 * GEN-CON-GCHAT-001: trusted DigitalMe session, Google account and consent gate.
 *
 * This is a pure integration contract. The resolvers must run inside trusted
 * Synnergyze server code and MUST NEVER accept client-supplied "verified" records.
 * A passed gate is necessary but NOT sufficient: Warden/River admission is
 * independently required immediately before any external MCP call.
 */
import { GOOGLE_CHAT_READ_SCOPES } from "./warden-read-gate.ts";
import type { TrustedGoogleChatPrincipalBinding } from "./oauth-transaction.ts";

export type VerifiedSynnergyzeSessionV1 = Readonly<{
  sessionRef: string;
  issuer: "synnergyze-session";
  audience: "genesis-google-chat-mcp";
  state: "ACTIVE" | "REVOKED" | "EXPIRED";
  actorRef: string;
  principalRef: string;
  actingCapacityRef: string;
  authenticatedAt: string;
  validUntil: string;
}>;

export type RegisteredGoogleAccountV1 = Readonly<{
  bindingRef: string;
  provider: "google";
  issuer: "https://accounts.google.com";
  lifecycle: "VERIFIED" | "PENDING" | "REVOKED";
  actorRef: string;
  principalRef: string;
  subject: string;
  enrollmentEvidenceRef: string;
  verifiedAt: string;
}>;

export type GoogleChatConsentV1 = Readonly<{
  consentRef: string;
  lifecycle: "ACTIVE" | "REVOKED" | "EXPIRED";
  actorRef: string;
  principalRef: string;
  googleAccountBindingRef: string;
  purpose: "google-chat-read-pilot";
  approvedScopes: readonly string[];
  allowedSpaceRefs: readonly string[];
  validFrom: string;
  validUntil: string;
}>;

/**
 * All implementations are privileged backend services.
 * verifyCurrentSession MUST validate its signed/authenticated session and
 * rotation/revocation state; no caller can provide a session object directly.
 */
export interface TrustedGoogleChatContextSourcesV1 {
  verifyCurrentSession(): Promise<VerifiedSynnergyzeSessionV1 | null>;
  findGoogleAccount(bindingRef: string): Promise<RegisteredGoogleAccountV1 | null>;
  findConsent(bindingRef: string): Promise<GoogleChatConsentV1 | null>;
}

export type GoogleChatTrustedContextInputV1 = Readonly<{
  accountBindingRef: string;
  targetSpaceRef: string;
  /** Generated by the internal Synnergyze orchestrator, not HTTP arguments. */
  wardenRequestRef: string;
  correlationId: string;
  now: string;
}>;

export type GoogleChatTrustedContextResultV1 =
  | Readonly<{ ok: false; code: string }>
  | Readonly<{
      ok: true;
      binding: TrustedGoogleChatPrincipalBinding;
      sessionRef: string;
      actingCapacityRef: string;
      targetSpaceRef: string;
      registeredGoogleSubject: string;
      consentValidUntil: string;
    }>;

function deny(code: string): GoogleChatTrustedContextResultV1 {
  return { ok: false, code };
}
function reference(value: string): boolean {
  return typeof value === "string" && value.length > 0 && value.length <= 256 &&
    !/[\x00-\x1f\x7f]/.test(value);
}
function instant(value: string): number | undefined {
  const parsed = Date.parse(value);
  return Number.isFinite(parsed) ? parsed : undefined;
}
function within(now: number, first: string, last: string): boolean {
  const start = instant(first), end = instant(last);
  return start !== undefined && end !== undefined &&
    start <= now && now < end && start < end;
}
function exactReadScopes(scopes: readonly string[]): boolean {
  if (!Array.isArray(scopes)) return false;
  const actual = new Set(scopes);
  return actual.size === GOOGLE_CHAT_READ_SCOPES.length &&
    GOOGLE_CHAT_READ_SCOPES.every(scope => actual.has(scope));
}

export async function resolveTrustedGoogleChatContextV1(
  sources: TrustedGoogleChatContextSourcesV1,
  request: GoogleChatTrustedContextInputV1,
): Promise<GoogleChatTrustedContextResultV1> {
  const now = instant(request.now);
  if (now === undefined) return deny("invalid_request_time");
  if (!reference(request.accountBindingRef) ||
      !reference(request.wardenRequestRef) || !reference(request.correlationId) ||
      !/^spaces\/[A-Za-z0-9_-]+$/.test(request.targetSpaceRef)) {
    return deny("invalid_request_scope");
  }

  try {
    const session = await sources.verifyCurrentSession();
    if (!session) return deny("session_not_verified");
    if (session.state !== "ACTIVE" || session.issuer !== "synnergyze-session" ||
        session.audience !== "genesis-google-chat-mcp") return deny("session_not_active");
    if (!reference(session.sessionRef) || !reference(session.actorRef) ||
        !reference(session.principalRef) || !reference(session.actingCapacityRef) ||
        !within(now, session.authenticatedAt, session.validUntil)) {
      return deny("session_expired_or_invalid");
    }

    const account = await sources.findGoogleAccount(request.accountBindingRef);
    if (!account || account.lifecycle !== "VERIFIED" || account.provider !== "google" ||
        account.issuer !== "https://accounts.google.com" ||
        account.bindingRef !== request.accountBindingRef ||
        account.actorRef !== session.actorRef || account.principalRef !== session.principalRef) {
      return deny("google_account_not_verified");
    }
    // Google's sub is an opaque case-sensitive identifier, NOT an email address.
    if (!reference(account.subject) || account.subject.length > 255 ||
        !reference(account.enrollmentEvidenceRef) ||
        instant(account.verifiedAt) === undefined ||
        instant(account.verifiedAt)! > now) {
      return deny("google_enrollment_invalid");
    }

    const consent = await sources.findConsent(request.accountBindingRef);
    if (!consent || consent.lifecycle !== "ACTIVE" ||
        consent.purpose !== "google-chat-read-pilot" ||
        consent.googleAccountBindingRef !== account.bindingRef ||
        consent.actorRef !== session.actorRef || consent.principalRef !== session.principalRef) {
      return deny("consent_not_active");
    }
    if (!reference(consent.consentRef) ||
        !within(now, consent.validFrom, consent.validUntil)) {
      return deny("consent_expired_or_invalid");
    }
    if (!exactReadScopes(consent.approvedScopes)) return deny("consent_scope_mismatch");
    if (!consent.allowedSpaceRefs.includes(request.targetSpaceRef)) {
      return deny("space_not_consented");
    }

    return {
      ok: true,
      binding: {
        actorRef: session.actorRef,
        principalRef: session.principalRef,
        googleAccountBindingRef: account.bindingRef,
        consentRef: consent.consentRef,
        wardenRequestRef: request.wardenRequestRef,
        correlationId: request.correlationId,
      },
      sessionRef: session.sessionRef,
      actingCapacityRef: session.actingCapacityRef,
      targetSpaceRef: request.targetSpaceRef,
      registeredGoogleSubject: account.subject,
      consentValidUntil: consent.validUntil,
    };
  } catch {
    // Trusted resolver outages or database errors are never a grant.
    return deny("trusted_context_unavailable");
  }
}
