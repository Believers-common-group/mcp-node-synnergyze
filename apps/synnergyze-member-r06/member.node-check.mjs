const PASSWORD='local-admin-password-2026';
async function setup(t){
 const dir=mkdtempSync(join(tmpdir(),'sy-r06-')),file=join(dir,'pilot.sqlite'),app=createMemberApp({file,adminPassword:PASSWORD});
 const url=await app.start();
 t.after(async()=>{await app.close();rmSync(dir,{recursive:true,force:true})});
 const req=async (path,body,headers={})=>{
   const response=await fetch(url+path,{method:body===undefined?'GET':'POST',headers:{...(body===undefined?{}:{'content-type':'application/json'}),...headers},body:body===undefined?undefined:JSON.stringify(body)});
   return {status:response.status,data:await response.json(),cookie:response.headers.get('set-cookie')?.split(';')[0]};
 };
 const auth=async (username,password)=>{const x=await req('/api/login',{username,password});assert.equal(x.status,200);
   return {cookie:x.cookie,csrf:x.data.csrf,headers(){return{cookie:this.cookie,'x-csrf':this.csrf}},async call(path,body={}){return req(path,body,this.headers())},async view(path){return req(path,undefined,{cookie:this.cookie})}}};
 return {dir,file,app,url,req,auth};
}
async function officeSetup(t){
 const x=await setup(t),office=await x.auth('office',PASSWORD);
 const a=(await office.call('/api/office/orgs',{name:'Business A'})).data.result;
 const b=(await office.call('/api/office/orgs',{name:'Business B'})).data.result;
 const c=(await office.call('/api/office/orgs',{name:'Business C'})).data.result;
 const invite=async(org,username)=>{
   const code=(await office.call('/api/office/invitations',{org_id:org.id})).data.result.invitation;
   assert.equal((await x.req('/api/join',{invitation:code,username,label:username,password:'member-password-2026'})).status,200);
   return x.auth(username,'member-password-2026');
 };
 const alice=await invite(a,'alice'),bob=await invite(b,'bob'),charlie=await invite(c,'charlie');
 const room=(await office.call('/api/office/rooms',{title:'Shared project',requester_org:a.id,partner_org:b.id})).data.result;
 return {x,office,alice,bob,charlie,room,a,b,c};
}
